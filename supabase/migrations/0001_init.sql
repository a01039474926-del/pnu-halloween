create or replace function public.admin_reset_demo(p_passcode text)
returns jsonb
language plpgsql
security definer
set search_path to 'public', 'extensions'
as $function$
declare
  v_hash text;
  v_deleted integer;
begin
  select value into v_hash from public.app_settings where key = 'admin_passcode_hash';
  if v_hash is null or extensions.crypt(coalesce(p_passcode, ''), v_hash) <> v_hash then
    perform pg_sleep(0.25);
    raise exception 'invalid passcode';
  end if;

  delete from public.analytics_events where session_id in (select id from public.sessions where is_demo);
  delete from public.orders where is_demo;
  get diagnostics v_deleted = row_count;
  delete from public.sessions where is_demo;

  return jsonb_build_object('ok', true, 'deleted_orders', v_deleted);
end;
$function$;

create or replace view public.v_funnel as
with counts as (
  select analytics_events.step_index,
         count(distinct analytics_events.session_id)::integer as sessions
    from public.analytics_events
   where analytics_events.event_name = 'funnel_step'
   group by analytics_events.step_index
)
select fs.step_index,
       fs.step_key,
       fs.step_label,
       coalesce(c.sessions, 0) as sessions,
       case
         when lag(coalesce(c.sessions, 0)) over (order by fs.step_index) is null then null::numeric
         when lag(coalesce(c.sessions, 0)) over (order by fs.step_index) = 0 then null::numeric
         else round((lag(coalesce(c.sessions, 0)) over (order by fs.step_index) - coalesce(c.sessions, 0))::numeric
           / lag(coalesce(c.sessions, 0)) over (order by fs.step_index)::numeric * 100::numeric, 1)
       end as dropoff_from_prev_pct
  from public.funnel_steps fs
  left join counts c using (step_index)
 order by fs.step_index;

create or replace view public.v_button_clicks as
select element_id,
       max(element_text) as element_text,
       max(section) as section,
       count(*)::integer as clicks,
       count(distinct session_id)::integer as sessions
  from public.analytics_events
 where event_name = 'button_click'
 group by element_id
 order by count(*)::integer desc;

create or replace view public.v_conversion as
select ((select count(*) from public.sessions))::integer as sessions,
       ((select count(*) from public.orders where status = 'paid'))::integer as orders,
       (select coalesce(sum(total_amount), 0) from public.orders where status = 'paid') as revenue,
       case
         when (select count(*) from public.sessions) = 0 then 0::numeric
         else round((select count(*) from public.orders where status = 'paid')::numeric
           / (select count(*) from public.sessions)::numeric * 100::numeric, 2)
       end as conversion_rate;

