create or replace function public.track_events(p_events jsonb)
returns integer
language plpgsql
security definer
set search_path to 'public', 'extensions'
as $function$
declare
  v_item jsonb;
  v_session uuid;
  v_inserted integer := 0;
  v_step integer;
  v_props jsonb;
begin
  if jsonb_typeof(p_events) <> 'array' then
    raise exception 'events must be an array';
  end if;
  if jsonb_array_length(p_events) > 30 then
    raise exception 'max 30 events per batch';
  end if;

  for v_item in select value from jsonb_array_elements(p_events) loop
    v_session := nullif(v_item->>'session_id', '')::uuid;
    if v_session is null then
      continue;
    end if;
    if not exists (select 1 from public.sessions where id = v_session) then
      continue;
    end if;
    if (select count(*) from public.analytics_events where session_id = v_session) >= 1500 then
      continue;
    end if;

    v_step := nullif(v_item->>'step_index', '')::integer;
    if v_step is not null and (v_step < 1 or v_step > 6) then
      v_step := null;
    end if;

    v_props := case
      when jsonb_typeof(coalesce(v_item->'properties', '{}'::jsonb)) = 'object'
       and length(coalesce(v_item->'properties', '{}'::jsonb)::text) <= 4000
      then coalesce(v_item->'properties', '{}'::jsonb)
      else jsonb_build_object('truncated', true)
    end;

    insert into public.analytics_events (
      session_id, visitor_id, event_name, step_index, page,
      element_id, element_text, section, properties
    ) values (
      v_session,
      nullif(v_item->>'visitor_id', '')::uuid,
      left(coalesce(nullif(v_item->>'event_name', ''), 'unknown'), 80),
      v_step,
      left(nullif(v_item->>'page', ''), 200),
      left(nullif(v_item->>'element_id', ''), 100),
      left(nullif(v_item->>'element_text', ''), 200),
      left(nullif(v_item->>'section', ''), 100),
      v_props
    );
    v_inserted := v_inserted + 1;
  end loop;

  update public.sessions
     set last_seen_at = now()
   where id in (
     select distinct (e->>'session_id')::uuid
       from jsonb_array_elements(p_events) e
      where e->>'session_id' is not null
   );

  return v_inserted;
end;
$function$;

