create or replace function public.create_order(p_payload jsonb)
returns jsonb
language plpgsql
security definer
set search_path to 'public', 'extensions'
as $function$
declare
  v_ticket   text := p_payload->>'ticket_type';
  v_qty      integer := coalesce(nullif(p_payload->>'quantity', '')::integer, 1);
  v_name     text := trim(coalesce(p_payload->>'buyer_name', ''));
  v_student  text := trim(coalesce(p_payload->>'student_id', ''));
  v_dept     text := trim(coalesce(p_payload->>'department', ''));
  v_phone    text := regexp_replace(coalesce(p_payload->>'phone', ''), '[^0-9]', '', 'g');
  v_session  uuid := nullif(p_payload->>'session_id', '')::uuid;
  v_visitor  uuid := nullif(p_payload->>'visitor_id', '')::uuid;
  v_price    integer;
  v_early_sold integer;
  v_order    public.orders;
begin
  if v_ticket is null or v_ticket not in ('early', 'regular') then
    raise exception 'invalid ticket type';
  end if;
  if v_qty < 1 or v_qty > 4 then
    raise exception 'invalid quantity';
  end if;
  if char_length(v_name) < 2 or char_length(v_name) > 40 then
    raise exception 'invalid name';
  end if;
  if v_student !~ '^[0-9]{6,12}$' then
    raise exception 'invalid student id';
  end if;
  if char_length(v_dept) < 1 or char_length(v_dept) > 60 then
    raise exception 'invalid department';
  end if;
  if char_length(v_phone) < 10 or char_length(v_phone) > 11 then
    raise exception 'invalid phone';
  end if;

  if v_ticket = 'early' then
    perform pg_advisory_xact_lock(918273645);
    select coalesce(sum(quantity), 0) into v_early_sold
      from public.orders
     where ticket_type = 'early' and status = 'paid' and is_demo = false;
    if v_early_sold + v_qty > 100 then
      raise exception 'early bird sold out';
    end if;
    v_price := 5000;
  else
    v_price := 8000;
  end if;

  insert into public.orders (
    order_no, session_id, visitor_id, buyer_name, student_id, department, phone,
    ticket_type, quantity, unit_price, total_amount
  ) values (
    'PNU' || to_char(now() at time zone 'Asia/Seoul', 'YYMMDD') || '-' ||
      upper(substr(encode(gen_random_bytes(3), 'hex'), 1, 5)),
    v_session, v_visitor, v_name, v_student, v_dept, v_phone,
    v_ticket, v_qty, v_price, v_price * v_qty
  )
  returning * into v_order;

  insert into public.analytics_events (
    session_id, visitor_id, event_name, step_index, page, element_id, element_text, section, properties
  ) values (
    v_session, v_visitor, 'purchase', 6, 'checkout', 'purchase_complete', '예매 확정', 'checkout',
    jsonb_build_object(
      'order_no', v_order.order_no,
      'ticket_type', v_ticket,
      'quantity', v_qty,
      'amount', v_order.total_amount
    )
  );

  return jsonb_build_object(
    'order_no', v_order.order_no,
    'ticket_type', v_ticket,
    'quantity', v_qty,
    'unit_price', v_price,
    'amount', v_order.total_amount,
    'created_at', v_order.created_at
  );
end;
$function$;

create or replace function public.admin_metrics(p_passcode text, p_days integer default 7)
returns jsonb
language plpgsql
security definer
set search_path to 'public', 'extensions'
as $function$
declare
  v_days integer := greatest(1, least(coalesce(p_days, 7), 90));
  v_since timestamptz := now() - make_interval(days => greatest(1, least(coalesce(p_days, 7), 90)));
  v_hash text;
  v_result jsonb;
begin
  select value into v_hash from public.app_settings where key = 'admin_passcode_hash';
  if v_hash is null or extensions.crypt(coalesce(p_passcode, ''), v_hash) <> v_hash then
    perform pg_sleep(0.25);
    raise exception 'invalid passcode';
  end if;

  with sess as (
    select * from public.sessions where started_at >= v_since
  ),
  ev as (
    select * from public.analytics_events where created_at >= v_since
  ),
  ord as (
    select * from public.orders
     where created_at >= v_since and status = 'paid'
  ),
  funnel_counts as (
    select step_index, count(distinct session_id)::integer as sessions
      from ev
     where event_name = 'funnel_step'
     group by step_index
  ),
  funnel_calc as (
    select
      fs.step_index,
      fs.step_key,
      fs.step_label,
      coalesce(fc.sessions, 0)::integer as sessions,
      lead(coalesce(fc.sessions, 0)::integer) over (order by fs.step_index) as next_sessions,
      first_value(coalesce(fc.sessions, 0)::integer) over (order by fs.step_index) as first_sessions
    from public.funnel_steps fs
    left join funnel_counts fc using (step_index)
  ),
  funnel as (
    select jsonb_agg(jsonb_build_object(
      'step_index', step_index,
      'step_key', step_key,
      'step_label', step_label,
      'sessions', sessions,
      'next_sessions', next_sessions,
      'dropoff_rate', case
        when next_sessions is null or sessions = 0 then 0
        else round(((sessions - next_sessions)::numeric / sessions) * 100, 1)
      end,
      'step_rate', case
        when first_sessions = 0 then 0
        else round((sessions::numeric / first_sessions) * 100, 1)
      end
    ) order by step_index) as data
    from funnel_calc
  ),
  day_series as (
    select generate_series(
      ((now() at time zone 'Asia/Seoul')::date - (v_days - 1)),
      (now() at time zone 'Asia/Seoul')::date,
      interval '1 day'
    )::date as d
  ),
  daily_sessions as (
    select (started_at at time zone 'Asia/Seoul')::date as d, count(*)::integer as n
      from sess group by 1
  ),
  daily_orders as (
    select (created_at at time zone 'Asia/Seoul')::date as d,
           count(*)::integer as n,
           coalesce(sum(total_amount), 0)::bigint as revenue
      from ord group by 1
  ),
  daily as (
    select jsonb_agg(jsonb_build_object(
      'date', to_char(ds.d, 'YYYY-MM-DD'),
      'sessions', coalesce(dse.n, 0),
      'orders', coalesce(dor.n, 0),
      'revenue', coalesce(dor.revenue, 0)
    ) order by ds.d) as data
    from day_series ds
    left join daily_sessions dse on dse.d = ds.d
    left join daily_orders dor on dor.d = ds.d
  ),
  button_calc as (
    select
      coalesce(element_id, 'unknown') as element_id,
      max(element_text) as element_text,
      max(section) as section,
      count(*)::integer as clicks,
      count(distinct session_id)::integer as sessions
    from ev
    where event_name = 'button_click'
    group by coalesce(element_id, 'unknown')
    order by clicks desc
    limit 12
  ),
  buttons as (
    select jsonb_agg(jsonb_build_object(
      'element_id', element_id,
      'element_text', element_text,
      'section', section,
      'clicks', clicks,
      'sessions', sessions,
      'ctr', case when (select count(*) from sess) = 0 then 0
                  else round((sessions::numeric / (select count(*) from sess)) * 100, 1) end
    ) order by clicks desc) as data
    from button_calc
  ),
  sess_src as (
    select
      s.id,
      coalesce(
        nullif(s.utm_source, ''),
        case
          when s.referrer is null or s.referrer = '' then 'direct'
          when s.referrer like '%localhost%' then 'local'
          else regexp_replace(regexp_replace(s.referrer, '^https?://', ''), '^www\.', '')
        end
      ) as raw_source
    from sess s
  ),
  sess_src_host as (
    select id, split_part(raw_source, '/', 1) as source from sess_src
  ),
  src_orders as (
    select ss.source,
           count(o.id)::integer as orders,
           coalesce(sum(o.total_amount), 0)::bigint as revenue
      from sess_src_host ss
      join ord o on o.session_id = ss.id
     group by ss.source
  ),
  src_sessions as (
    select source, count(*)::integer as n from sess_src_host group by source
  ),
  sources as (
    select jsonb_agg(jsonb_build_object(
      'source', ss.source,
      'sessions', ss.n,
      'orders', coalesce(so.orders, 0),
      'revenue', coalesce(so.revenue, 0),
      'conversion_rate', case when ss.n = 0 then 0
                              else round((coalesce(so.orders, 0)::numeric / ss.n) * 100, 1) end
    ) order by ss.n desc) as data
    from src_sessions ss
    left join src_orders so using (source)
  ),
  device_sessions as (
    select coalesce(device_type, 'unknown') as device_type, count(*)::integer as n
      from sess group by 1
  ),
  device_orders as (
    select coalesce(s.device_type, 'unknown') as device_type,
           count(o.id)::integer as orders
      from ord o
      join sess s on s.id = o.session_id
     group by 1
  ),
  devices as (
    select jsonb_agg(jsonb_build_object(
      'device_type', d.device_type,
      'sessions', d.n,
      'orders', coalesce(dord.orders, 0),
      'conversion_rate', case when d.n = 0 then 0
                              else round((coalesce(dord.orders, 0)::numeric / d.n) * 100, 1) end
    ) order by d.n desc) as data
    from device_sessions d
    left join device_orders dord using (device_type)
  ),
  ticket_agg as (
    select ticket_type,
           count(*)::integer as cnt,
           coalesce(sum(quantity), 0)::integer as qty,
           coalesce(sum(total_amount), 0)::bigint as revenue
      from ord
     group by ticket_type
  ),
  tickets as (
    select jsonb_agg(jsonb_build_object(
      'ticket_type', ticket_type,
      'orders', cnt,
      'quantity', qty,
      'revenue', revenue
    ) order by ticket_type) as data
    from ticket_agg
  ),
  recent as (
    select jsonb_agg(jsonb_build_object(
      'order_no', order_no,
      'buyer', left(buyer_name, 1) || repeat('*', greatest(char_length(buyer_name) - 1, 1)),
      'department', department,
      'phone', '***-' || right(phone, 4),
      'ticket_type', ticket_type,
      'quantity', quantity,
      'amount', total_amount,
      'created_at', created_at
    ) order by created_at desc) as data
    from (
      select * from ord order by created_at desc limit 8
    ) r
  ),
  kpis as (
    select jsonb_build_object(
      'sessions', (select count(*) from sess),
      'visitors', (select count(distinct visitor_id) from sess),
      'page_views', (select count(*) from ev where event_name = 'page_view'),
      'orders', (select count(*) from ord),
      'revenue', (select coalesce(sum(total_amount), 0) from ord),
      'conversion_rate', case when (select count(*) from sess) = 0 then 0
                              else round(((select count(*) from ord)::numeric / (select count(*) from sess)) * 100, 2) end,
      'aov', case when (select count(*) from ord) = 0 then 0
                  else round((select coalesce(sum(total_amount), 0) from ord)::numeric / (select count(*) from ord)) end,
      'total_clicks', (select count(*) from ev where event_name = 'button_click'),
      'form_errors', (select count(*) from ev where event_name = 'form_error'),
      'live_sessions', (select count(*) from public.sessions where last_seen_at > now() - interval '5 minutes'),
      'demo_sessions', (select count(*) from public.sessions where is_demo),
      'demo_orders', (select count(*) from public.orders where is_demo),
      'checkout_reach', (select count(distinct session_id) from ev where event_name = 'funnel_step' and step_index = 5),
      'apply_reach', (select count(distinct session_id) from ev where event_name = 'funnel_step' and step_index = 4)
    ) as data
  )
  select jsonb_build_object(
    'generated_at', now(),
    'range_days', v_days,
    'kpis', (select data from kpis),
    'funnel', coalesce((select data from funnel), '[]'::jsonb),
    'daily', coalesce((select data from daily), '[]'::jsonb),
    'buttons', coalesce((select data from buttons), '[]'::jsonb),
    'sources', coalesce((select data from sources), '[]'::jsonb),
    'devices', coalesce((select data from devices), '[]'::jsonb),
    'ticket_mix', coalesce((select data from tickets), '[]'::jsonb),
    'recent_orders', coalesce((select data from recent), '[]'::jsonb)
  ) into v_result;

  return v_result;
end;
$function$;

